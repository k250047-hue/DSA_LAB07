
#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;

int qCount = 0;
int mCount = 0;

void showArray(const vector<int>& nums, int start, int end)
{
    cout << "[";
    for (int i = start; i <= end; i++)
    {
        cout << nums[i];
        if (i < end)
            cout << ", ";
    }
    cout << "]";
}

int makePartition(vector<int>& nums, int start, int end)
{
    int key = nums[end];
    int pos = start - 1;

    for (int j = start; j < end; j++)
    {
        if (nums[j] <= key)
        {
            pos++;
            swap(nums[pos], nums[j]);
        }
    }

    swap(nums[pos + 1], nums[end]);
    int pivotPos = pos + 1;

    cout << "Selected pivot: " << key << endl;

    cout << "Left subarray: ";
    if (start < pivotPos)
    {
        showArray(nums, start, pivotPos - 1);
        qCount++;
    }
    else
        cout << "[]";

    cout << endl << "Pivot: [" << nums[pivotPos] << "]" << endl;

    cout << "Right subarray: ";
    if (pivotPos < end)
    {
        showArray(nums, pivotPos + 1, end);
        qCount++;
    }
    else
        cout << "[]";

    cout << "\n\n";
    return pivotPos;
}

void quickSort(vector<int>& nums, int start, int end)
{
    if (start < end)
    {
        int pivotPos = makePartition(nums, start, end);
        quickSort(nums, start, pivotPos - 1);
        quickSort(nums, pivotPos + 1, end);
    }
}

void mergeParts(vector<int>& nums, int start, int mid, int end)
{
    vector<int> leftPart(nums.begin() + start, nums.begin() + mid + 1);
    vector<int> rightPart(nums.begin() + mid + 1, nums.begin() + end + 1);
    vector<int> sortedPart;

    int a = 0, b = 0;

    while (a < leftPart.size() && b < rightPart.size())
    {
        if (leftPart[a] <= rightPart[b])
            sortedPart.push_back(leftPart[a++]);
        else
            sortedPart.push_back(rightPart[b++]);
    }

    while (a < leftPart.size())
        sortedPart.push_back(leftPart[a++]);

    while (b < rightPart.size())
        sortedPart.push_back(rightPart[b++]);

    for (int k = 0; k < sortedPart.size(); k++)
        nums[start + k] = sortedPart[k];

    cout << "Merged subarray: ";
    showArray(nums, start, end);
    cout << endl;
}

void mergeSort(vector<int>& nums, int start, int end)
{
    if (start >= end)
        return;

    int mid = start + (end - start) / 2;

    cout << "Dividing ";
    showArray(nums, start, end);
    cout << " into ";

    showArray(nums, start, mid);
    cout << " and ";
    showArray(nums, mid + 1, end);
    cout << endl;

    mCount += 2;

    mergeSort(nums, start, mid);
    mergeSort(nums, mid + 1, end);

    mergeParts(nums, start, mid, end);
}

int main()
{
    int size;

    cout << "Enter number of elements (at least 10): ";
    cin >> size;

    if (size < 10)
    {
        cout << "Please enter at least 10 elements." << endl;
        return 0;
    }

    vector<int> data(size);

    cout << "Enter " << size << " elements: ";
    for (int i = 0; i < size; i++)
        cin >> data[i];

    vector<int> qArray = data;
    vector<int> mArray = data;

    cout << "\n--- QUICK SORT ---\n";
    quickSort(qArray, 0, size - 1);

    cout << "Total subarrays generated by Quick Sort: "
         << qCount << endl;

    cout << "Final sorted array: ";
    showArray(qArray, 0, size - 1);

    cout << "\n\n--- MERGE SORT ---\n";
    mergeSort(mArray, 0, size - 1);

    cout << "Total subarrays generated during Merge Sort division: "
         << mCount << endl;

    cout << "Final sorted array: ";
    showArray(mArray, 0, size - 1);

    cout << endl;
    return 0;
}